import type { ReleaseEntry } from "../content/releases";

const escapeXml = (value: string): string =>
  value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&apos;");

const list = (title: string, items: readonly string[]): string =>
  items.length ? `<h3>${escapeXml(title)}</h3><ul>${items.map((item) => `<li>${escapeXml(item)}</li>`).join("")}</ul>` : "";

/** The release as the HTML body of one feed entry (escaped once more by `escapeXml` when embedded). */
export function releaseHtml(release: ReleaseEntry): string {
  const { verified, notYetVerified, knownLimits } = release.scientificStatus;
  return [
    `<p>${escapeXml(release.summary)}</p>`,
    list("Added", release.added),
    list("Changed", release.changed),
    list("Fixed", release.fixed),
    list("Verified", verified.map((claim) => `${claim.statement} (${claim.platform}; ${claim.engine})`)),
    list("Not yet verified", notYetVerified),
    list("Known limits", knownLimits),
  ].join("");
}

/** An Atom 1.0 feed generated by hand from the release data; entries keep the order of `releases` (newest first). */
export function buildAtomFeed(releases: readonly ReleaseEntry[], options: { siteUrl: string; locale: string }): string {
  const site = options.siteUrl.replace(/\/+$/, "");
  const page = `${site}/${options.locale}/releases`;
  const host = new URL(site).hostname;
  const first = releases[0];
  const updated = first ? `${first.date}T00:00:00Z` : "1970-01-01T00:00:00Z";
  const entries = releases.map((release) =>
    [
      "  <entry>",
      `    <id>tag:${host},${release.date}:release-${release.version}</id>`,
      `    <title>${escapeXml(`ChemDFT ${release.version}: ${release.title}`)}</title>`,
      `    <updated>${release.date}T00:00:00Z</updated>`,
      `    <link rel="alternate" type="text/html" href="${escapeXml(`${page}#${release.version}`)}"/>`,
      `    <summary>${escapeXml(release.summary)}</summary>`,
      `    <content type="html">${escapeXml(releaseHtml(release))}</content>`,
      "  </entry>",
    ].join("\n"),
  );
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<feed xmlns="http://www.w3.org/2005/Atom">',
    `  <id>tag:${host},2026:chemdft-releases</id>`,
    "  <title>ChemDFT release notes</title>",
    `  <updated>${updated}</updated>`,
    `  <link rel="self" type="application/atom+xml" href="${escapeXml(`${page}/feed.xml`)}"/>`,
    `  <link rel="alternate" type="text/html" href="${escapeXml(page)}"/>`,
    "  <author><name>Tabriz Ahmadli</name></author>",
    ...entries,
    "</feed>",
    "",
  ].join("\n");
}
