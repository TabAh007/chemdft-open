import { expect, test } from "@playwright/test";
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { choosePlanMode } from "./ai-composer";

// Planning uses the existing fake model provider. ALL scientific results come from real PySCF.
const root = "/api/chemdft/v1";
const shots = resolve("../../output/playwright/b42");
test.setTimeout(180_000);
test.use({ viewport: { width: 1600, height: 1100 } });

test("B4.2: human approval → real H2 execution → automatic grounded result → persisted browser report", async ({ page, request }) => {
  mkdirSync(shots, { recursive: true });
  expect(process.env.CHEMDFT_E2E_WORKER_MODE).toBe("enabled");
  const created = await request.post(`${root}/projects`, { data: { name: "B4.2 · real H2 quantum acceptance", slug: `b42-${crypto.randomUUID()}` } });
  expect(created.status()).toBe(201);
  const projectId = (await created.json()).id;
  const base = `${root}/projects/${projectId}`;
  const imported = await request.post(`${base}/structures/imports`, {
    multipart: { upload: { name: "h2.xyz", mimeType: "chemical/x-xyz", buffer: Buffer.from("2\nH2 user-supplied geometry; 0.74 angstrom\nH 0 0 -0.37\nH 0 0 0.37\n") }, file_format: "XYZ", idempotency_key: crypto.randomUUID(), structure_name: "H2 · supplied geometry" },
  });
  expect(imported.status()).toBe(201);
  const structure = await imported.json();
  expect((await request.put(`${root}/ai/settings`, { data: { mode: "MANAGED", provider: "fake", model: "fake-standard" } })).ok()).toBe(true);
  await page.goto(`/en/projects/${projectId}/workspace`);
  const show = page.getByRole("button", { name: "Show AI Scientist panel", exact: true });
  if (await show.isVisible()) await show.click();
  const panel = page.getByTestId("ai-scientist-panel");
  await expect(panel).toBeVisible();
  await expect(page.getByTestId("ai-prompt-input")).toBeEnabled({ timeout: 40_000 });
  await page.getByTestId("ai-prompt-input").fill("Calculate the HF/STO-3G single-point energy for H2.");
  await choosePlanMode(page, { general: false });
  await page.getByTestId("ai-prepare-calculation-button").click();
  const plan = page.getByTestId("ai-calculation-proposal");
  await expect(plan).toContainText(structure.version.id, { timeout: 40_000 });
  await expect(plan).toContainText("AVAILABLE");
  await plan.screenshot({ path: resolve(shots, "01-human-approval.png") });
  expect((await (await request.get(`${base}/compute/jobs`)).json()).jobs).toHaveLength(0);
  const decision = page.waitForResponse(response => response.url().includes("/approvals/") && response.url().endsWith("/decision"));
  await page.getByTestId("ai-approve-button").click();
  const response = await decision;
  expect(response.status()).toBe(200);
  const submitted = await response.json();
  expect(submitted.status).toBe("WAITING_FOR_CALCULATION");
  const calculationId = submitted.waiting_calculation_id;
  const resultPanel = page.getByTestId("ai-calculation-result");
  await expect(resultPanel.getByTestId("energy-readout-value")).toHaveText("-1.1167593074", { timeout: 60_000 });
  await expect(page.getByTestId("ai-scientific-workflow")).toContainText("Completed · SUCCEEDED", { timeout: 20_000 });
  const detail = await (await request.get(`${base}/calculations/${calculationId}`)).json();
  const run = await (await request.get(`${base}/ai/runs/${submitted.id}`)).json();
  expect(detail.calculation.state).toBe("SUCCEEDED");
  expect(detail.compute_job.state).toBe("SUCCEEDED");
  expect(detail.compute_execution.state).toBe("FINISHED");
  expect(detail.result.payload.total_energy.unit.code).toBe("Eh");
  expect(detail.result.payload.total_energy.value).toBeCloseTo(-1.1167593073964255, 10);
  expect(detail.result.payload.converged).toBe(true);
  expect(detail.result.producer_software.name).toBe("pyscf");
  expect(detail.result.producer_software.version).toBe("2.14.0");
  await resultPanel.getByText("Calculation parameters & provenance", { exact: true }).click();
  await expect(resultPanel).toContainText(structure.version.id);
  await expect(resultPanel).toContainText(structure.version.origin);
  await expect(resultPanel).toContainText("Coordinate origin unavailable");
  await expect(resultPanel).toContainText("Not independently verified");
  const conversation = await (await request.get(`${base}/ai/conversations/${run.conversation_id}`)).json();
  const finalMessage = conversation.messages.at(-1);
  expect(finalMessage.evidence_status).toBe("SUPPORTED");
  expect(finalMessage.content).toContain(`${detail.result.payload.total_energy.value} Eh`);
  expect(finalMessage.citations[0].entity_id).toBe(calculationId);
  await expect(panel).toContainText("Authoritative energy:");
  const events = (await (await request.get(`${base}/ai/runs/${run.id}/events`)).json()).events;
  expect(events.filter((event: { event_type: string }) => event.event_type === "calculation.result_available")).toHaveLength(1);
  writeFileSync(resolve(shots, "result-panel.txt"), await resultPanel.innerText());
  await resultPanel.getByText("Calculation parameters & provenance", { exact: true }).click();
  await resultPanel.getByTestId("energy-readout-value").scrollIntoViewIfNeeded();
  const readout = resultPanel.getByTestId("energy-readout-value");
  expect(await readout.evaluate(element => getComputedStyle(element).whiteSpace)).toBe("nowrap");
  // Hold this reading position across actual server polls; result review must not jump to chat.
  const scrollRegion = page.locator(".ai-conversation-scroll");
  const readingPosition = await scrollRegion.evaluate(element => element.scrollTop);
  await page.waitForResponse(response => response.url().endsWith(`/ai/runs/${run.id}`) && response.request().method() === "GET");
  expect(Math.abs(await scrollRegion.evaluate(element => element.scrollTop) - readingPosition)).toBeLessThan(2);
  await panel.screenshot({ path: resolve(shots, "02-real-h2-result.png") });
  await page.screenshot({ path: resolve(shots, "03-workstation-completed.png"), fullPage: true });
  const artifacts = [];
  for (const artifact of detail.result.raw_artifacts) {
    const downloaded = await request.get(`${base}/calculations/${calculationId}/artifacts/${artifact.artifact_id}`);
    expect(downloaded.status()).toBe(200);
    const file = `native-${artifact.artifact_id}.txt`;
    writeFileSync(resolve(shots, file), await downloaded.body());
    artifacts.push({ ...artifact, evidenceFile: file });
  }
  writeFileSync(resolve(shots, "acceptance.json"), JSON.stringify({ planningProvider: "fake (planning only)", quantumComputation: "REAL PYSCF 2.14.0", workspace: process.env.CHEMDFT_TEST_WORKSPACE, projectId, structure, detail, run, finalMessage, events, artifacts }, null, 2));
  await page.addScriptTag({ path: resolve("node_modules/axe-core/axe.min.js") });
  const accessibility = await page.evaluate(async () => (window as unknown as { axe: { run: (context: string, options: object) => Promise<{ violations: { impact: string; id: string }[] }> } }).axe.run('[data-testid="ai-calculation-result"]', { runOnly: { type: "tag", values: ["wcag2a", "wcag2aa"] } }));
  writeFileSync(resolve(shots, "accessibility.json"), JSON.stringify(accessibility, null, 2));
  expect(accessibility.violations.filter(item => ["serious", "critical"].includes(item.impact))).toEqual([]);
  await page.reload();
  if (await show.isVisible()) await show.click();
  await expect(resultPanel.getByTestId("energy-readout-value")).toHaveText("-1.1167593074", { timeout: 30_000 });
  await expect(panel).toContainText("Authoritative energy:");
  await page.route(`**/calculations/${calculationId}`, route => route.abort());
  await expect(resultPanel.getByTestId("energy-readout-value")).toHaveCount(0, { timeout: 10_000 });
  await expect(page.getByRole("button", { name: "Reload calculation", exact: true })).toBeVisible();
  await page.unroute(`**/calculations/${calculationId}`);
  await page.getByRole("button", { name: "Reload calculation", exact: true }).click();
  await expect(resultPanel.getByTestId("energy-readout-value")).toHaveText("-1.1167593074");
  await page.setViewportSize({ width: 820, height: 1180 });
  await resultPanel.getByTestId("energy-readout-value").scrollIntoViewIfNeeded();
  expect(await readout.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await panel.screenshot({ path: resolve(shots, "04-tablet-result.png") });
  expect(await resultPanel.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.setViewportSize({ width: 1600, height: 1100 });
  await resultPanel.getByRole("button", { name: "Inspect calculation & artifacts", exact: true }).click();
  await expect(page.getByText("-1.1167593074", { exact: true }).first()).toBeVisible();
  await page.screenshot({ path: resolve(shots, "05-calculation-workspace.png"), fullPage: true });
});
