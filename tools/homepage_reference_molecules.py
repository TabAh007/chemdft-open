"""Validate the homepage reference molecules and generate the bundled structure data.

Sources (nothing here is a ChemDFT calculation):

* water  - ChemDFT's own stored test geometry, ``services/api/tests/fixtures/structures/test-user-supplied-water.xyz``
           (the geometry behind the real PySCF water calculation shown on the homepage).
* benzene, caffeine - PubChem 3D conformers (CID 241, CID 2519), downloaded once from the PubChem PUG REST service
           (``.../compound/cid/<cid>/SDF?record_type=3d``) and committed unmodified under
           ``apps/web/src/app/_components/home/reference/molecules/``. The homepage never calls PubChem at runtime.

Each source is parsed through ChemDFT's own RDKit structure adapter (the path user uploads take), sanitised with RDKit,
checked against the expected formula and InChIKey, and checked geometrically (bond lengths, planarity, clashes).

    uv run --project services/api python tools/homepage_reference_molecules.py
"""

from __future__ import annotations

import itertools
import json
import math
from pathlib import Path

from chemdft_api.scientific.adapters.molecular.rdkit_adapter import parse_sdf, parse_xyz
from rdkit import Chem
from rdkit.Chem import rdMolDescriptors

ROOT = Path(__file__).resolve().parents[1]
REFERENCE = ROOT / "apps/web/src/app/_components/home/reference"
MOLECULES = REFERENCE / "molecules"
WATER_XYZ = ROOT / "services/api/tests/fixtures/structures/test-user-supplied-water.xyz"
OUT = REFERENCE / "molecules.json"

# Covalent radii (Cordero et al., Dalton Trans. 2008, 2832) used only to sanity-check bond lengths.
COVALENT = {"H": 0.31, "C": 0.76, "N": 0.71, "O": 0.66}

SPEC = {
    "benzene": {
        "file": MOLECULES / "pubchem-cid-241-benzene.sdf",
        "title": "Benzene",
        "formula": "C6H6",
        "inchikey": "UHOVQNZJYSORNB-UHFFFAOYSA-N",
        "cid": 241,
        "atoms": 12,
        "bonds": 12,
    },
    "caffeine": {
        "file": MOLECULES / "pubchem-cid-2519-caffeine.sdf",
        "title": "Caffeine",
        "formula": "C8H10N4O2",
        "inchikey": "RYYVLZVUVIJVGH-UHFFFAOYSA-N",
        "cid": 2519,
        "atoms": 24,
        "bonds": 25,
    },
}

PUBCHEM_SOURCE = {
    "name": "PubChem",
    "url": "https://pubchem.ncbi.nlm.nih.gov/compound/{cid}",
    "kind": "3D conformer computed by PubChem (not an experimental structure and not a ChemDFT calculation)",
    "retrieval": "PUG REST: compound/cid/{cid}/SDF?record_type=3d (retrieved once, committed unmodified)",
    "licence": (
        "NCBI places no restrictions on use or distribution of PubChem data; third-party submitters may claim "
        "rights in submitted content (https://www.ncbi.nlm.nih.gov/home/about/policies/). These are common, "
        "long-established compounds; the 3D conformer is generated by PubChem. NLM is acknowledged."
    ),
}


def _distance(a: dict, b: dict) -> float:
    return math.dist((a["x"], a["y"], a["z"]), (b["x"], b["y"], b["z"]))


def _plane_rms(atoms: list[dict]) -> float:
    """RMS distance of the atoms from their best-fit plane (smallest-variance direction)."""
    n = len(atoms)
    cx, cy, cz = (sum(a[k] for a in atoms) / n for k in ("x", "y", "z"))
    cov = [[0.0] * 3 for _ in range(3)]
    for a in atoms:
        v = (a["x"] - cx, a["y"] - cy, a["z"] - cz)
        for i in range(3):
            for j in range(3):
                cov[i][j] += v[i] * v[j] / n
    # smallest eigenvector by power iteration on (trace*I - cov)
    trace = sum(cov[i][i] for i in range(3))
    m = [[(trace if i == j else 0.0) - cov[i][j] for j in range(3)] for i in range(3)]
    vec = [1.0, 0.7, 0.3]
    for _ in range(200):
        nxt = [sum(m[i][j] * vec[j] for j in range(3)) for i in range(3)]
        norm = math.sqrt(sum(c * c for c in nxt))
        vec = [c / norm for c in nxt]
    deviations = [
        (a["x"] - cx) * vec[0] + (a["y"] - cy) * vec[1] + (a["z"] - cz) * vec[2] for a in atoms
    ]
    return math.sqrt(sum(d * d for d in deviations) / n)


def _geometry_checks(atoms: list[dict], bonds: list[dict]) -> dict:
    bonded = {(min(b["atom_index_a"], b["atom_index_b"]), max(b["atom_index_a"], b["atom_index_b"])) for b in bonds}
    lengths = []
    for b in bonds:
        a1, a2 = atoms[b["atom_index_a"]], atoms[b["atom_index_b"]]
        length = _distance(a1, a2)
        ideal = COVALENT[a1["element"]] + COVALENT[a2["element"]]
        assert abs(length - ideal) < 0.30, (a1["element"], a2["element"], length, ideal)
        lengths.append(round(length, 4))
    clashes = [
        (i, j)
        for i, j in itertools.combinations(range(len(atoms)), 2)
        if (i, j) not in bonded and _distance(atoms[i], atoms[j]) < 1.5 - 0.3 * (atoms[i]["element"] == "H" or atoms[j]["element"] == "H")
    ]
    # 1-3 neighbours (through two bonds) are legitimately ~2.0-2.5 A apart; only flag closer-than-covalent contacts
    clashes = [(i, j) for i, j in clashes if _distance(atoms[i], atoms[j]) < 0.9 * (COVALENT[atoms[i]["element"]] + COVALENT[atoms[j]["element"]])]
    assert not clashes, clashes
    return {"bond_length_range_angstrom": [min(lengths), max(lengths)], "bonded_pairs_checked": len(lengths)}


def _molecule_from_pubchem(key: str, spec: dict) -> dict:
    data = spec["file"].read_bytes()
    candidate = parse_sdf(data)  # ChemDFT's validated molecular import path (raises on invalid input)
    coordinates = candidate.coordinates
    atoms = [
        {"element": a["element"], "x": round(a["x"], 4), "y": round(a["y"], 4), "z": round(a["z"], 4)}
        for a in coordinates["atoms"]
    ]
    bonds = [
        {"atom_index_a": b["atom_index_a"], "atom_index_b": b["atom_index_b"], "order": b["order"]}
        for b in coordinates["bonds"]
    ]
    mol = Chem.MolFromMolBlock(data.decode(), sanitize=True, removeHs=False)
    assert mol is not None
    assert rdMolDescriptors.CalcMolFormula(mol) == spec["formula"], rdMolDescriptors.CalcMolFormula(mol)
    assert Chem.MolToInchiKey(mol) == spec["inchikey"], Chem.MolToInchiKey(mol)
    assert len(atoms) == spec["atoms"] and len(bonds) == spec["bonds"]
    assert candidate.overall_charge == 0
    checks = _geometry_checks(coordinates["atoms"], bonds)
    ring_atoms = [a for a in coordinates["atoms"] if a["element"] != "H"]
    if key == "benzene":
        carbon = [a for a in coordinates["atoms"] if a["element"] == "C"]
        assert sum(1 for b in mol.GetBonds() if b.GetIsAromatic()) == 6
        checks["carbon_ring_planarity_rms_angstrom"] = round(_plane_rms(carbon), 5)
        assert checks["carbon_ring_planarity_rms_angstrom"] < 0.005
    else:
        checks["heavy_atom_planarity_rms_angstrom"] = round(_plane_rms(ring_atoms), 4)
    return {
        "id": f"pubchem-cid-{spec['cid']}-{key}",
        "title": spec["title"],
        "formula": spec["formula"],
        "inchikey": spec["inchikey"],
        "charge": 0,
        "source": {**PUBCHEM_SOURCE, "id": f"CID {spec['cid']}", "url": PUBCHEM_SOURCE["url"].format(cid=spec["cid"]), "retrieval": PUBCHEM_SOURCE["retrieval"].format(cid=spec["cid"])},
        "connectivity": "SDF bond table (authoritative in the source record)",
        "atoms": atoms,
        "bonds": bonds,
        "validation": {
            "chemdft_adapter": "chemdft.rdkit.molecular parse_sdf",
            "rdkit_sanitised": True,
            "formula": spec["formula"],
            "inchikey_matches": True,
            "atoms": len(atoms),
            "bonds": len(bonds),
            **checks,
        },
    }


def _water() -> dict:
    data = WATER_XYZ.read_bytes()
    candidate = parse_xyz(data)  # ChemDFT's validated XYZ import path
    atoms = [
        {"element": a["element"], "x": round(a["x"], 6), "y": round(a["y"], 6), "z": round(a["z"], 6)}
        for a in candidate.coordinates["atoms"]
    ]
    assert [a["element"] for a in atoms] == ["O", "H", "H"]
    o, h1, h2 = (candidate.coordinates["atoms"][i] for i in range(3))
    d1, d2 = _distance(o, h1), _distance(o, h2)
    v1 = (h1["x"] - o["x"], h1["y"] - o["y"], h1["z"] - o["z"])
    v2 = (h2["x"] - o["x"], h2["y"] - o["y"], h2["z"] - o["z"])
    angle = math.degrees(math.acos(sum(a * b for a, b in zip(v1, v2)) / (d1 * d2)))
    assert abs(d1 - 0.9572) < 1e-4 and abs(d2 - 0.9572) < 1e-4
    assert abs(angle - 104.52) < 0.01, angle
    return {
        "id": "chemdft-test-water",
        "title": "Water",
        "formula": "H2O",
        "charge": 0,
        "source": {
            "name": "ChemDFT repository test geometry",
            "id": "services/api/tests/fixtures/structures/test-user-supplied-water.xyz",
            "kind": "Gas-phase test geometry used by ChemDFT's accepted water calculations (not itself a calculation result)",
            "licence": "Part of the ChemDFT repository.",
        },
        "connectivity": "None in the source (XYZ); display bonds are inferred from distances by the renderer",
        "atoms": atoms,
        "bonds": [],
        "validation": {
            "chemdft_adapter": "chemdft.rdkit.molecular parse_xyz",
            "atoms": 3,
            "o_h_distances_angstrom": [round(d1, 4), round(d2, 4)],
            "h_o_h_angle_degrees": round(angle, 3),
        },
    }


def main() -> None:
    report = {"water": _water(), **{key: _molecule_from_pubchem(key, spec) for key, spec in SPEC.items()}}
    OUT.write_text(json.dumps(report, indent=1) + "\n")
    print(json.dumps({k: v["validation"] for k, v in report.items()}, indent=1))


if __name__ == "__main__":
    main()
