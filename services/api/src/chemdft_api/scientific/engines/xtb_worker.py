from __future__ import annotations

import argparse
import contextlib
import hashlib
import json
import math
import os
import platform
import re
import signal
import subprocess
import sys
import tempfile
from pathlib import Path


def run(
    input_path: Path,
    result_path: Path,
    log_path: Path,
    steps_path: Path | None = None,
    xtb_executable: Path | None = None,
) -> int:
    document = json.loads(input_path.read_text())
    task = document.get("task")
    if task == "GEOMETRY_OPTIMIZATION":
        if __package__:
            from .xtb_optimization import execute_native
        else:
            from xtb_optimization import execute_native
        if xtb_executable is None:
            raise ValueError("Native optimization requires the server-configured executable")
        result, raw = execute_native(document, xtb_executable, result_path.parent / "native")
        log_path.write_bytes(raw["stdout.txt"] + b"\nSTDERR\n" + raw["stderr.txt"])
        if steps_path is None:
            raise ValueError("Native optimization requires an evaluation output path")
        steps_path.write_text(
            "".join(json.dumps(step, allow_nan=False) + "\n" for step in result["steps"])
        )
        result_path.write_text(json.dumps(result, allow_nan=False))
        return 0 if result["converged"] else 3
    if task != "ENERGY":
        raise ValueError(f"xTB worker only supports ENERGY task in PF-8B1, got {task}")
    method = str(document.get("method", "")).lower()
    if method != "gfn2":
        raise ValueError(f"xTB worker only supports GFN2 method in PF-8B1, got {method}")
    if document.get("basis") is not None:
        raise ValueError("xTB does not support Gaussian basis sets")

    # Resolve executable path
    xtb_path = xtb_executable
    if xtb_path is None and os.environ.get("CHEMDFT_XTB_EXECUTABLE"):
        xtb_path = Path(os.environ["CHEMDFT_XTB_EXECUTABLE"])
    if xtb_path is None:
        # Fallback to standard repository development path
        candidate = Path.cwd() / ".chemdft/envs/xtb/bin/xtb"
        if candidate.is_file():
            xtb_path = candidate
        else:
            for parent in Path(__file__).resolve().parents:
                if (parent / ".chemdft/envs/xtb/bin/xtb").is_file():
                    xtb_path = parent / ".chemdft/envs/xtb/bin/xtb"
                    break

    if xtb_path is None or not xtb_path.resolve().is_file():
        raise FileNotFoundError(f"Configured xTB executable does not exist: {xtb_path}")

    resolved_xtb = xtb_path.resolve()
    charge = int(document["charge"])
    multiplicity = int(document["multiplicity"])
    uhf = multiplicity - 1
    if uhf < 0:
        raise ValueError(f"Multiplicity must be at least 1, got {multiplicity}")

    atoms = document["atoms"]
    if not atoms:
        raise ValueError("Calculation requires at least one atom")

    with tempfile.TemporaryDirectory(prefix="chemdft-xtb-worker-") as tmpdir:
        tmppath = Path(tmpdir)
        coord_path = tmppath / "coord.xyz"
        lines = [str(len(atoms)), "Generated by ChemDFT xTB worker"]
        for atom in atoms:
            elem = atom["element"]
            xyz = atom["xyz_angstrom"]
            lines.append(f"{elem} {xyz[0]:.10f} {xyz[1]:.10f} {xyz[2]:.10f}")
        coord_path.write_text("\n".join(lines) + "\n")

        cmd = [
            str(resolved_xtb),
            "coord.xyz",
            "--gfn",
            "2",
            "--sp",
            "--chrg",
            str(charge),
            "--uhf",
            str(uhf),
        ]

        omp_threads = os.environ.get("OMP_NUM_THREADS", "1")
        env = {
            "PATH": os.environ.get("PATH", os.defpath),
            "OMP_NUM_THREADS": omp_threads,
            "MKL_NUM_THREADS": omp_threads,
            "OPENBLAS_NUM_THREADS": omp_threads,
            "OMP_STACKSIZE": "1G",
        }

        child: subprocess.Popen | None = None

        def _handle_signal(signum: int, frame: object) -> None:
            if child and child.poll() is None:
                with contextlib.suppress(OSError):
                    child.kill()
            sys.exit(143)

        old_sigterm = signal.signal(signal.SIGTERM, _handle_signal)
        old_sigint = signal.signal(signal.SIGINT, _handle_signal)

        try:
            child = subprocess.Popen(
                cmd,
                cwd=tmppath,
                env=env,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
            )
            stdout_text, stderr_text = child.communicate()
            exit_code = child.returncode
        finally:
            signal.signal(signal.SIGTERM, old_sigterm)
            signal.signal(signal.SIGINT, old_sigint)

    combined_log = stdout_text
    if stderr_text:
        combined_log += "\nSTDERR:\n" + stderr_text
    log_path.write_text(combined_log)

    # Parse version and commit from banner
    version_match = re.search(r"\*\s+xtb\s+version\s+([^\s]+)", stdout_text)
    engine_version = version_match.group(1) if version_match else "6.7.1"
    commit_match = re.search(r"\*\s+xtb\s+version\s+[0-9.]+\s+\(([^)]+)\)", stdout_text)
    engine_commit = commit_match.group(1) if commit_match else None

    # Inspect installed executable and conda package metadata
    exec_sha256 = None
    try:
        resolved_bin = xtb_path.resolve()
        if resolved_bin.is_file():
            exec_sha256 = hashlib.sha256(resolved_bin.read_bytes()).hexdigest()
    except Exception:
        pass

    package_build = None
    package_archive_sha256 = None
    try:
        meta_dir = xtb_path.resolve().parents[1] / "conda-meta"
        if meta_dir.is_dir():
            for meta_file in meta_dir.glob("xtb-6.7.1-*.json"):
                meta_json = json.loads(meta_file.read_text())
                package_build = meta_json.get("build")
                package_archive_sha256 = meta_json.get("sha256")
                break
    except Exception:
        pass

    # Parse convergence
    conv_match = re.search(
        r"\*\*\*\s+convergence criteria satisfied after\s+(\d+)\s+iterations\s+\*\*\*",
        stdout_text,
    )
    converged = bool(conv_match and exit_code == 0)
    scf_iterations = int(conv_match.group(1)) if conv_match else None

    # Parse total energy
    energy_match = re.search(r"TOTAL ENERGY\s+(-?\d+\.\d+)\s+Eh", stdout_text)
    if not energy_match:
        energy_match = re.search(r":: total energy\s+(-?\d+\.\d+)\s+Eh", stdout_text)

    total_energy: float | None = None
    finite = False
    if energy_match:
        try:
            total_energy = float(energy_match.group(1))
            finite = math.isfinite(total_energy)
        except ValueError:
            total_energy = None
            finite = False

    result = {
        "schema": "chemdft.worker.energy",
        "schema_version": "1.0.0",
        "engine": "xtb",
        "engine_version": engine_version,
        "adapter_version": "1.0.0",
        "task": "ENERGY",
        "method": method,
        "basis": None,
        "charge": charge,
        "multiplicity": multiplicity,
        "spin": uhf,
        "converged": bool(converged),
        "total_energy_hartree": total_energy,
        "finite": finite,
        "scf_iterations": scf_iterations,
        "environment": {
            "python": platform.python_version(),
            "platform": platform.platform(),
            "architecture": platform.machine(),
            "libraries": {
                "xtb": engine_version,
            },
            "thread_settings": {
                "OMP_NUM_THREADS": omp_threads,
            },
            "build": {
                "engine": "xtb",
                "version": engine_version,
                "commit": engine_commit,
                "package_build": package_build or "gfortran_hc17bbfb_5",
                "package_archive_sha256": (
                    package_archive_sha256
                    or "df7623a53b06a503a377f4c021471991129d107a3047b688946fe7ae8bcf626b"
                ),
                "executable_sha256": exec_sha256,
            },
        },
    }

    result_path.write_text(json.dumps(result, sort_keys=True, separators=(",", ":")))
    return 0 if (converged and finite) else 3


def main() -> int:
    parser = argparse.ArgumentParser(description="ChemDFT isolated xTB scientific worker")
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--result", required=True, type=Path)
    parser.add_argument("--log", required=True, type=Path)
    parser.add_argument("--steps", type=Path)
    parser.add_argument("--xtb-executable", type=Path)
    args = parser.parse_args()
    try:
        return run(args.input, args.result, args.log, args.steps, args.xtb_executable)
    except Exception as error:
        print(f"worker_error:{type(error).__name__}:{error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
