NO_HUBBARD_LABEL_MESSAGE = (
    "The pseudopotential for {element} ({file}) has no {shell} projector label, so +U on {element} is not "
    "available with this library."
)


def pseudo_for_element(symbol: str) -> dict | None:
    row = SSSP_EFFICIENCY_V2.get(symbol)
    if row is None:
        return None
    file, kind, z_val, wfc, rho, lib, labels, mass = row
    return {
        "element": symbol,
        "file": file,
        "type": kind,
        "z_valence": z_val,
        "ecutwfc_ry": float(wfc),
        "ecutrho_ry": float(rho),
        "library": lib,
        "hubbard_labels": labels,
        "mass": mass,
    }


def unsupported_element_message(symbol: str) -> str:
    reason = UNOFFERED_ELEMENTS.get(symbol)
    if reason:
        return f"Quantum ESPRESSO periodic: element {symbol} is not offered ({reason})."
    return f"Quantum ESPRESSO periodic: element {symbol} has no pseudopotential in {PSEUDO_LIBRARY_NAME}."


# +U is offered on 3d transition metals only (the shell the PySCF worker and the default-U table use).
HUBBARD_3D_ELEMENTS = frozenset({"Sc", "Ti", "V", "Cr", "Mn", "Fe", "Co", "Ni", "Cu", "Zn"})


def hubbard_label_available(symbol: str, shell: str = "3D") -> bool:
    """True when the pseudopotential file carries a PP_CHI projector with this label (checked on the real UPFs)."""
    row = SSSP_EFFICIENCY_V2.get(symbol)
    return bool(row) and shell.upper() in row[6]
